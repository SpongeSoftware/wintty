"""Regenerate docs/src/content/docs/themes.md from the bundled theme files.

Run from the repository root after adding or changing a file in src/Wintty.Core/Themes:

    python scripts/gen-themes-doc.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
themes = root / "src" / "Wintty.Core" / "Themes"
out = root / "docs" / "src" / "content" / "docs" / "themes.md"


def colours(path):
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        key, _, value = line.partition("=")
        key = key.strip()
        if key in ("background", "foreground"):
            values[key] = value.strip()
    return values.get("background", ""), values.get("foreground", "")


rows = []
for path in sorted(themes.iterdir(), key=lambda p: p.name.lower()):
    background, foreground = colours(path)
    rows.append(f"| {path.name} | `{background}` | `{foreground}` |")

out.write_text(
    f"""---
title: Themes
description: Every colour theme built into wintty.
---

Set a theme with `theme = <name>` in the [config file](/wintty/configuration/). Names ignore case, and spaces, hyphens and underscores are interchangeable, so `theme = catppuccin-mocha` finds Catppuccin Mocha.

wintty bundles the {len(rows) - 3} themes Ghostty ships (including Catppuccin Latte, Frappe, Macchiato and Mocha, and Gruvbox Dark and Light) plus **Bamboo**, **Bamboo Multiplex** and **Bamboo Light**, derived from the [bamboo.nvim](https://github.com/ribru17/bamboo.nvim) colours. See `NOTICE` in the repository for licences.

To add your own, save a file in `%APPDATA%\\wintty\\themes\\` named after the theme. It uses the same `key = value` format; `background`, `foreground`, `cursor-color` and `palette = N=#rrggbb` lines are read. A file there with the same name as a built-in theme replaces it.

This page is generated by `scripts/gen-themes-doc.py`.

| Theme | Background | Foreground |
| --- | --- | --- |
"""
    + "\n".join(rows)
    + "\n",
    encoding="utf-8",
    newline="\n",
)
print(f"wrote {out} with {len(rows)} themes")
